@pytest.mark.asyncio
async def test_cancel_narrows_to_creator_or_owner(
    collab_hunt, as_member: AsyncClient, as_curator: AsyncClient, as_owner: AsyncClient
) -> None:
    visit_id = (await _create(as_member, collab_hunt)).json()["id"]

    # A Curator is not the creator: cancelling someone else's visit is not theirs
    # to do, even though they may answer every item on it (DESIGN §4.2).
    denied = await as_curator.patch(f"/v1/visits/{visit_id}", json={"action": "cancel"})
    assert denied.status_code == 403
    assert denied.json()["code"] == "cannot_cancel_visit"

    # The Owner may.
    cancelled = await as_owner.patch(f"/v1/visits/{visit_id}", json={"action": "cancel"})
    assert cancelled.status_code == 200

    reinstated = await as_member.patch(f"/v1/visits/{visit_id}", json={"action": "reinstate"})
    assert reinstated.status_code == 200
    assert reinstated.json()["state"] == "planned"


