"""Visit lifecycle and unit endpoints (VC-1, DESIGN §9.7, §4.2)."""

from __future__ import annotations

import pytest
from httpx import AsyncClient
from manzil_api.visits.template import TEMPLATE_VERSION


async def _create(client: AsyncClient, collab_hunt, **overrides):  # type: ignore[no-untyped-def]
    payload = {"property_id": collab_hunt["owner_property_id"], **overrides}
    return await client.post(f"/v1/hunts/{collab_hunt['hunt_id']}/visits", json=payload)


@pytest.mark.asyncio
async def test_create_visit_spanning_a_planned_and_a_described_unit(
    collab_hunt, as_member: AsyncClient
) -> None:
    created = await _create(
        as_member,
        collab_hunt,
        units=[
            # Backed by a Floor Plan: beds/baths come from the plan, so the Unit
            # Group key matches the listing's own grouping.
            {"label": "4B", "floor_plan_id": collab_hunt["owner_plan_id"], "display_order": 0},
            # A unit the listing never advertised — the normal case, not an error.
            {"label": "the corner one", "beds": 1, "baths": 1.5, "display_order": 1},
        ],
    )
    assert created.status_code == 201, created.text
    body = created.json()
    assert body["state"] == "planned"
    assert body["template_version"] == TEMPLATE_VERSION
    assert body["started_at"] is None

    units = {unit["label"]: unit for unit in body["units"]}
    # Derived by the database from the Floor Plan's own beds/baths, so the key
    # matches the listing's grouping rather than anything the client sent.
    assert units["4B"]["unit_group_key"] == "1-1"
    assert units["4B"]["floor_plan_id"] == collab_hunt["owner_plan_id"]
    # Generated by the database, and normalized: 1.5 baths stays "1-1.5" while a
    # whole number must not become "1-1.0" or the roll-up joins nothing.
    assert units["the corner one"]["unit_group_key"] == "1-1.5"
    assert units["the corner one"]["floor_plan_id"] is None


