@pytest.mark.asyncio
async def test_reopening_never_re_resolves_the_frozen_template(
    collab_hunt, as_owner: AsyncClient, db_pool
) -> None:
    """`template_version` is immutable, so a finished tour cannot change meaning."""
    visit = (await _create(as_owner, collab_hunt)).json()
    await as_owner.patch(f"/v1/visits/{visit['id']}", json={"action": "start"})
    await as_owner.patch(f"/v1/visits/{visit['id']}", json={"action": "end"})
    before = await db_pool.fetchval(
        "select template_version from visits where id = $1", visit["id"]
    )

    await as_owner.patch(f"/v1/visits/{visit['id']}", json={"action": "reopen"})
    after = await db_pool.fetchval("select template_version from visits where id = $1", visit["id"])
    assert after == before
