@pytest.mark.asyncio
async def test_reopening_a_finished_visit_makes_it_editable_again(
    collab_hunt, as_owner: AsyncClient
) -> None:
    """Ending is a state, not a seal (DESIGN §9.7).

    A tour is written on a phone and read on a desktop, and the desktop is where
    the typo gets fixed and the half-heard answer finally gets typed.
    """
    visit = (await _create(as_owner, collab_hunt)).json()
    await as_owner.patch(f"/v1/visits/{visit['id']}", json={"action": "start"})
    ended = await as_owner.patch(f"/v1/visits/{visit['id']}", json={"action": "end"})
    assert ended.json()["state"] == "completed"

    reopened = await as_owner.patch(f"/v1/visits/{visit['id']}", json={"action": "reopen"})
    assert reopened.status_code == 200, reopened.text
    assert reopened.json()["state"] == "in_progress"
    # VC-9: the tour ended when it ended. Reopening records a *second* event
    # rather than erasing the first, so the 42 minutes it actually took survives.
    assert reopened.json()["ended_at"] == ended.json()["ended_at"]
    assert reopened.json()["reopened_at"] is not None
    # The tour still knows when it started; reopening is not restarting.
    assert reopened.json()["started_at"] is not None


